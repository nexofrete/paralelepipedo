def opamp(in2, nome, flip=True):
    o = elm.Opamp(leads=True)
    if flip:
        o = o.flip()
    o = o.theta(0).anchor("in2").at(in2).label(nome, loc="center", fontsize=8)
    d.add(o)
    return o


def reostato(a, b, ref, val, lado="top"):
    return two(elm.ResistorVar, a, b, ref, val, lado)


